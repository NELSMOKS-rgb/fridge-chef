const fs=require('fs');const path=require('path');
const root=path.join(__dirname,'..');
const vm=require('vm');const ctx={};vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root,'vocab.js'),'utf8')+';this.VOCAB=VOCAB;',ctx);
const V=ctx.VOCAB;
const lines=['recipes1.txt','recipes2.txt','recipes3.txt'].flatMap(f=>fs.readFileSync(path.join(root,f),'utf8').split('\n')).filter(l=>l.trim());
const T={b:'breakfast',l:'lunch',d:'dinner',s:'snack',x:'dessert'};
const out=[];const bad=[];const names=new Set();
lines.forEach((l,i)=>{const p=l.split('|');if(p.length!==6){bad.push('fields '+p.length+': '+l.slice(0,60));return;}
 const [name,types,mins,diet,ings,steps]=p;
 if(names.has(name))bad.push('dup '+name);names.add(name);
 const I=ings.split(',').map(s=>{let opt=false;s=s.trim();if(s[0]==='~'){opt=true;s=s.slice(1);}const [k,q='']=s.split('=');if(!V[k.trim()])bad.push(name+': unknown '+k);return {k:k.trim(),q:q.trim(),o:opt?1:0};});
 types.split(',').forEach(t=>{if(!T[t])bad.push(name+': type '+t)});
 if(!['','v','vg'].includes(diet))bad.push(name+': diet '+diet);
 out.push({id:'r'+(i+1),n:name,t:types.split(',').map(t=>T[t]),m:+mins,v:diet==='v'?1:diet==='vg'?2:0,i:I,s:steps.split(';').map(s=>s.trim()).filter(Boolean)});
});
if(bad.length){console.log(bad.join('\n'));process.exit(1);}
fs.writeFileSync(path.join(root,'recipes.js'),'// '+out.length+' built-in recipes (generated by tools/build-data.js)\nconst RECIPES='+JSON.stringify(out)+';\n');
console.log('ok',out.length,'recipes', 'veg',out.filter(r=>r.v).length,'quick',out.filter(r=>r.m<30).length);
